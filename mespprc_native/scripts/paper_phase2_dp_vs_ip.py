"""
Paper-grade Phase 2 DP vs IP benchmark, both implementations in C.

Design (so the table is meaningful as evidence in a technical paper):

  - Both algorithms run in compiled C. Phase 2 DP is the route-network
    labeling DP from `mespprc_native/src/phase2_dp.c`. Phase 2 IP is the
    set-partitioning MIP solved by HiGHS from
    `mespprc_native/src/phase2_ip.c`. The Python implementations only
    appear as oracles in the equivalence checks elsewhere; they are not
    timed here.

  - Phase 1 is run once per replicate inside the C library and the
    resulting handle is fed to BOTH Phase 2 solvers, so the only
    independent variable between DP and IP is the Phase 2 algorithm
    (pool reduction + solve). Instance generation is excluded from
    timings, matching the rest of the benchmark harness in the repo.

  - For each customer count n we draw `replicates` independent seeds.
    The same seed produces the same instance, so DP and IP see byte-
    identical input. Instances are generated by
    `mespprc.generate_instance` with `GeneratorConfig(num_customers=n,
    seed=...)`.

  - DP timing is gated by `--dp-timeout-seconds`. Once a single
    replicate's DP runtime exceeds the cap, we skip DP for the rest of
    that n and for every larger n. IP keeps going until `--max-n` or
    `--ip-timeout-seconds`.

  - The script writes three artefacts under `results/`:
        * `native_dp_vs_ip.csv`        per-replicate raw data
        * `native_dp_vs_ip_summary.md` summary table + conclusions
        * `native_dp_vs_ip.png`        log-y scaling plot (DP + IP + crossover)

The conclusions section in the Markdown report is generated from the
data that this run actually produced — not from prior knowledge baked
into the script. If the data changes, the conclusions change.
"""

